using System.Text;

namespace Folio.Gen;

/// <summary>
/// Generates C# binding code from an IdlDocument written against IScriptEngine and Folio.Scripting only.
/// Never references Jint or any backend-specific types.
/// </summary>
public static class IdlCodeGenerator
{
    private static readonly object GenerationLock = new();
    private static IReadOnlyDictionary<string, IdlType> _aliases = new Dictionary<string, IdlType>();
    private static IReadOnlySet<string> _enumNames = new HashSet<string>();
    private static IReadOnlySet<string> _dictionaryNames = new HashSet<string>();
    public static string Generate(IdlDocument doc, string targetNamespace = "Folio.Scripting.Bindings")
    {
        lock (GenerationLock)
            return GenerateCore(doc, targetNamespace);
    }

    private static string GenerateCore(IdlDocument doc, string targetNamespace)
    {
        _aliases = (doc.Typedefs ?? []).ToDictionary(x => x.Name, x => x.Type, StringComparer.Ordinal);
        _enumNames = doc.Enums.Select(x => x.Name).ToHashSet(StringComparer.Ordinal);
        _dictionaryNames = doc.Dictionaries.Select(x => x.Name).ToHashSet(StringComparer.Ordinal);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Generated by tools/Folio.Gen from WebIDL descriptions. Do not edit.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Linq;");
        if (doc.Interfaces.Any(i => i.Attributes.Any(a => a.SameObject)))
            sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using Folio.Scripting;");
        sb.AppendLine();
        sb.AppendLine($"namespace {targetNamespace};");
        sb.AppendLine();

        // 1. Enums
        foreach (var idlEnum in doc.Enums)
        {
            GenerateEnum(sb, idlEnum);
        }

        // 2. Dictionaries
        foreach (var dict in doc.Dictionaries)
        {
            GenerateDictionary(sb, dict);
        }

        // 3. Interfaces (C# interface + Binding class producing IHostObjectTemplate)
        foreach (var iface in doc.Interfaces)
        {
            GenerateInterface(sb, iface);
        }

        return sb.ToString();
    }

    private static void GenerateEnum(StringBuilder sb, IdlEnum idlEnum)
    {
        sb.AppendLine($"public static class {idlEnum.Name}");
        sb.AppendLine("{");
        foreach (var val in idlEnum.Values)
        {
            var propName = ToPascalCase(val);
            sb.AppendLine($"    public const string {propName} = \"{val}\";");
        }
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void GenerateDictionary(StringBuilder sb, IdlDictionary dict)
    {
        var inheritClause = dict.Inherits is not null ? $" : {dict.Inherits}" : "";
        sb.AppendLine($"public class {dict.Name}{inheritClause}");
        sb.AppendLine("{");
        foreach (var member in dict.Members)
        {
            var csType = MapCsType(member.Type);
            var propName = ToPascalCase(member.Name);
            var defVal = member.DefaultValue is not null ? $" = {FormatDefaultValue(member.Type, member.DefaultValue)};" : "";
            sb.AppendLine($"    public {csType} {propName} {{ get; set; }}{defVal}");
        }
        sb.AppendLine();
        sb.AppendLine($"    public static {dict.Name} FromScriptValue(IScriptEngine? engine, ScriptValue value)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var dict = new {dict.Name}();");
        sb.AppendLine("        if (value.IsNullOrUndefined) return dict;");
        sb.AppendLine("        WebIdlConversions.RequireObject(value, \"dictionary\");");
        sb.AppendLine("        var actualEngine = WebIdlConversions.RequireEngine(engine);");
        foreach (var member in dict.Members)
        {
            var propName = ToPascalCase(member.Name);
            var conversion = GenerateValueConversion(member.Type, $"memberVal_{propName}");
            sb.AppendLine($"        var memberVal_{propName} = actualEngine.GetProperty(value, \"{member.Name}\");");
            if (member.IsRequired)
                sb.AppendLine($"        if (memberVal_{propName}.IsUndefined) throw WebIdlException.TypeError(\"Missing required dictionary member '{member.Name}'\");");
            if (member.DefaultValue is not null)
                sb.AppendLine($"        dict.{propName} = memberVal_{propName}.IsUndefined ? {FormatDefaultValue(member.Type, member.DefaultValue)} : {conversion};");
            else
                sb.AppendLine($"        if (!memberVal_{propName}.IsUndefined) dict.{propName} = {conversion};");
        }
        sb.AppendLine("        return dict;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public ScriptValue ToScriptValue(IScriptEngine? engine)");
        sb.AppendLine("    {");
        sb.AppendLine("        var properties = new Dictionary<string, ScriptValue>(StringComparer.Ordinal);");
        foreach (var member in dict.Members)
        {
            var propName = ToPascalCase(member.Name);
            var converted = GenerateToScriptValue(member.Type, propName);
            sb.AppendLine($"        properties[\"{member.Name}\"] = {converted};");
        }
        sb.AppendLine("        return WebIdlConversions.RequireEngine(engine).CreatePlainObject(properties);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void GenerateInterface(StringBuilder sb, IdlInterface iface)
    {
        // Emit C# target interface (e.g. ITestTarget or I{Name})
        var targetInterfaceName = $"I{iface.Name}Target";
        var inheritClause = iface.Inherits is not null ? $" : I{iface.Inherits}Target" : "";
        sb.AppendLine($"public interface {targetInterfaceName}{inheritClause}");
        sb.AppendLine("{");

        // Constants
        foreach (var c in iface.Constants)
        {
            var csType = MapCsType(c.Type);
            sb.AppendLine($"    const {csType} {c.Name} = {c.Value};");
        }

        // Attributes
        foreach (var attr in iface.Attributes)
        {
            var csType = MapCsType(attr.Type);
            var propName = ToPascalCase(attr.Name);
            var getter = "get;";
            var setter = attr.IsReadOnly ? "" : " set;";
            sb.AppendLine($"    {csType} {propName} {{ {getter}{setter} }}");
        }

        // Operations
        foreach (var op in iface.Operations)
        {
            var retType = op.ReturnType.Name == "undefined" ? "void" : MapCsType(op.ReturnType);
            var opName = ToPascalCase(op.Name);
            var args = string.Join(", ", op.Arguments.Select(a =>
            {
                var argType = a.IsVariadic ? $"IReadOnlyList<{MapCsType(a.Type)}>" : MapCsType(a.Type);
                return $"{argType} {ToCamelCase(a.Name)}";
            }));
            sb.AppendLine($"    {retType} {opName}({args});");
        }

        // Indexed / Named
        if (iface.IndexedGetter is not null)
            sb.AppendLine($"    {MapCsType(iface.IndexedGetter.ReturnType)} GetItem(uint index);");
        if (iface.IndexedSetter is not null)
            sb.AppendLine($"    void SetItem(uint index, {MapCsType(iface.IndexedSetter.ValueType)} value);");
        if (iface.NamedGetter is not null)
            sb.AppendLine($"    {MapCsType(iface.NamedGetter.ReturnType)} GetNamedItem(string name);");
        if (iface.NamedSetter is not null)
            sb.AppendLine($"    void SetNamedItem(string name, {MapCsType(iface.NamedSetter.ValueType)} value);");
        if (iface.NamedDeleter is not null)
            sb.AppendLine("    void DeleteNamedItem(string name);");

        sb.AppendLine("}");
        sb.AppendLine();

        // Emit Template Builder
        sb.AppendLine($"public static class {iface.Name}Binding");
        sb.AppendLine("{");
        sb.AppendLine($"    public static ScriptValue CreateObject(IScriptEngine engine, {targetInterfaceName} target) => WebIdlConversions.WrapHostObject(engine, CreateTemplate(engine), target);");
        sb.AppendLine($"    public static HostObjectTemplate CreateTemplate(IHostObjectTemplate? proto = null) => CreateTemplate(null, proto);");
        sb.AppendLine($"    public static HostObjectTemplate CreateTemplate(IScriptEngine? engine, IHostObjectTemplate? proto = null)");
        sb.AppendLine("    {");
        sb.AppendLine($"        if (engine is not null && proto is null) return WebIdlConversions.GetOrCreateTemplate(engine, \"{iface.Name}\", () => CreateTemplateCore(engine, null));");
        sb.AppendLine("        return CreateTemplateCore(engine, proto);");
        sb.AppendLine("    }");
        sb.AppendLine($"    private static HostObjectTemplate CreateTemplateCore(IScriptEngine? engine, IHostObjectTemplate? proto)");
        sb.AppendLine("    {");
        if (iface.Inherits is not null)
            sb.AppendLine($"        proto ??= {iface.Inherits}Binding.CreateTemplate(engine);");
        sb.AppendLine($"        var template = new HostObjectTemplate(\"{iface.Name}\", proto);");
        foreach (var sameObjectAttribute in iface.Attributes.Where(a => a.SameObject))
            sb.AppendLine($"        var sameObjectCache_{ToPascalCase(sameObjectAttribute.Name)} = new ConditionalWeakTable<object, StrongBox<ScriptValue>>();");

        // Constants on template
        foreach (var c in iface.Constants)
        {
            sb.AppendLine($"        template.DefineProperty(\"{c.Name}\", (target, thisVal) => ScriptValue.FromNumber({c.Value}));");
        }

        // Attributes
        foreach (var attr in iface.Attributes)
        {
            var propName = ToPascalCase(attr.Name);
            var returnScriptVal = GenerateToScriptValue(attr.Type, "result");

            string? setterCode = null;
            if (!attr.IsReadOnly)
            {
                var convertedVal = GenerateValueConversion(attr.Type, "val");
                setterCode = $"(target, thisVal, val) => (( {targetInterfaceName} )target).{propName} = {convertedVal}";
            }

            if (setterCode is not null)
            {
                sb.AppendLine($"        template.DefineProperty(\"{attr.Name}\",");
                sb.AppendLine("            (target, thisVal) =>");
                sb.AppendLine("            {");
                sb.AppendLine($"                if (target is not {targetInterfaceName} typedTarget) throw WebIdlException.TypeError(\"Illegal invocation\");");
                if (attr.SameObject)
                {
                    sb.AppendLine($"                if (sameObjectCache_{propName}.TryGetValue(target, out var cached)) return cached.Value;");
                    sb.AppendLine($"                var result = typedTarget.{propName};");
                    sb.AppendLine($"                var wrapped = {returnScriptVal};");
                    sb.AppendLine($"                sameObjectCache_{propName}.Add(target, new StrongBox<ScriptValue>(wrapped));");
                    sb.AppendLine("                return wrapped;");
                }
                else
                {
                    sb.AppendLine($"                var result = typedTarget.{propName};");
                    sb.AppendLine($"                return {returnScriptVal};");
                }
                sb.AppendLine("            },");
                sb.AppendLine($"            {setterCode});");
            }
            else
            {
                sb.AppendLine($"        template.DefineProperty(\"{attr.Name}\",");
                sb.AppendLine("            (target, thisVal) =>");
                sb.AppendLine("            {");
                sb.AppendLine($"                if (target is not {targetInterfaceName} typedTarget) throw WebIdlException.TypeError(\"Illegal invocation\");");
                if (attr.SameObject)
                {
                    sb.AppendLine($"                if (sameObjectCache_{propName}.TryGetValue(target, out var cached)) return cached.Value;");
                    sb.AppendLine($"                var result = typedTarget.{propName};");
                    sb.AppendLine($"                var wrapped = {returnScriptVal};");
                    sb.AppendLine($"                sameObjectCache_{propName}.Add(target, new StrongBox<ScriptValue>(wrapped));");
                    sb.AppendLine("                return wrapped;");
                }
                else
                {
                    sb.AppendLine($"                var result = typedTarget.{propName};");
                    sb.AppendLine($"                return {returnScriptVal};");
                }
                sb.AppendLine("            });");
            }
        }

        // Operations
        // Group by operation name for overload resolution
        var opsByName = iface.Operations.GroupBy(o => o.Name);
        foreach (var opGroup in opsByName)
        {
            var opName = opGroup.Key;
            var pascalName = ToPascalCase(opName);

            sb.AppendLine($"        template.DefineMethod(\"{opName}\", (target, thisVal, args) =>");
            sb.AppendLine("        {");
            sb.AppendLine($"            if (target is not {targetInterfaceName} typedTarget)");
            sb.AppendLine("                throw WebIdlException.TypeError(\"Illegal invocation\");");
            sb.AppendLine();

            var overloads = opGroup.ToList();
            if (overloads.Count == 1)
            {
                var op = overloads[0];
                sb.AppendLine($"            if (args.Length < {RequiredArgumentCount(op)}) throw WebIdlException.TypeError(\"Not enough arguments\");");
                GenerateOperationCall(sb, op, pascalName);
            }
            else
            {
                foreach (var op in overloads.OrderByDescending(RequiredArgumentCount))
                {
                    var min = RequiredArgumentCount(op);
                    var max = op.Arguments.Any(a => a.IsVariadic) ? int.MaxValue : op.Arguments.Count;
                    var shape = OverloadShapeCondition(op, overloads);
                    // WebIDL ignores trailing arguments; overload selection uses the
                    // required prefix and distinguishing argument types.
                    sb.AppendLine($"            if (args.Length >= {min}{shape})");
                    sb.AppendLine("            {");
                    GenerateOperationCall(sb, op, pascalName, indent: "                ");
                    sb.AppendLine("            }");
                }
                sb.AppendLine("            throw WebIdlException.TypeError(\"No matching overload found\");");
            }

            sb.AppendLine("        });");
        }

        sb.AppendLine("        return template;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void GenerateOperationCall(StringBuilder sb, IdlOperation op, string pascalName, string indent = "            ")
    {
        var callArgs = new List<string>();
        for (var i = 0; i < op.Arguments.Count; i++)
        {
            var arg = op.Arguments[i];
            var argVar = $"arg_{arg.Name}";
            if (arg.IsVariadic)
            {
                var itemConversion = GenerateValueConversion(arg.Type, "item");
                sb.AppendLine($"{indent}var {argVar} = args.Skip({i}).Select(item => {itemConversion}).ToArray();");
                callArgs.Add(argVar);
                continue;
            }
            var argRaw = $"args.Length > {i} ? args[{i}] : ScriptValue.Undefined";
            sb.AppendLine($"{indent}var raw_{arg.Name} = {argRaw};");

            if (arg.IsOptional && arg.DefaultValue is not null)
            {
                sb.AppendLine($"{indent}var {argVar} = raw_{arg.Name}.IsUndefined ? {FormatDefaultValue(arg.Type, arg.DefaultValue)} : {GenerateValueConversion(arg.Type, $"raw_{arg.Name}")};");
            }
            else if (arg.IsOptional)
            {
                sb.AppendLine($"{indent}var {argVar} = raw_{arg.Name}.IsUndefined ? default : {GenerateValueConversion(arg.Type, $"raw_{arg.Name}")};");
            }
            else
            {
                sb.AppendLine($"{indent}var {argVar} = {GenerateValueConversion(arg.Type, $"raw_{arg.Name}")};");
            }
            callArgs.Add(argVar);
        }

        var callExpr = $"typedTarget.{pascalName}({string.Join(", ", callArgs)})";
        if (op.ReturnType.Name == "undefined" || op.ReturnType.Name == "void")
        {
            sb.AppendLine($"{indent}{callExpr};");
            sb.AppendLine($"{indent}return ScriptValue.Undefined;");
        }
        else
        {
            sb.AppendLine($"{indent}var result = {callExpr};");
            sb.AppendLine($"{indent}return {GenerateToScriptValue(op.ReturnType, "result")};");
        }
    }

    private static string MapCsType(IdlType type)
    {
        type = Resolve(type);
        var baseType = type.Name switch
        {
            "void" or "undefined" => "void",
            "boolean" => "bool",
            "byte" => "sbyte",
            "octet" => "byte",
            "short" => "short",
            "unsigned short" => "ushort",
            "long" => "int",
            "unsigned long" => "uint",
            "long long" => "long",
            "unsigned long long" => "ulong",
            "float" => "float",
            "unrestricted float" => "float",
            "double" => "double",
            "unrestricted double" => "double",
            "DOMString" or "ByteString" or "USVString" => "string",
            "any" => "ScriptValue",
            "object" => "ScriptValue",
            "BufferSource" or "ArrayBuffer" or "ArrayBufferView" or "DataView" => "ScriptBufferSource",
            "sequence" => $"IReadOnlyList<{MapCsType(type.SubTypes![0])}>",
            "record" => $"IReadOnlyDictionary<{MapCsType(type.SubTypes![0])}, {MapCsType(type.SubTypes![1])}>",
            "union" => "ScriptValue",
            _ when type.Kind == IdlTypeKind.Enum => "string",
            "Promise" => $"Task<{MapCsType(type.SubTypes![0])}>",
            _ when type.Kind == IdlTypeKind.TypedArray => "ScriptBufferSource",
            _ when _dictionaryNames.Contains(type.Name) => type.Name,
            _ when _enumNames.Contains(type.Name) => "string",
            _ => $"I{type.Name}Target",
        };

        if (type.IsNullable)
            return $"{baseType}?";
        return baseType;
    }

    private static string GenerateValueConversion(IdlType type, string varName)
    {
        type = Resolve(type);
        if (type.IsNullable)
        {
            return $"{varName}.IsNullOrUndefined ? ({MapCsType(type)})null : {GenerateValueConversion(type with { IsNullable = false }, varName)}";
        }
        if (type.Kind == IdlTypeKind.Enum)
            return $"WebIdlConversions.ToDOMString(engine, {varName})";

        return type.Name switch
        {
            "boolean" => $"WebIdlConversions.ToBoolean(engine, {varName})",
            "DOMString" or "ByteString" => $"WebIdlConversions.ToDOMString(engine, {varName})",
            "USVString" => $"WebIdlConversions.ToUSVString(engine, {varName})",
            "double" => $"WebIdlConversions.ToDouble(engine, {varName})",
            "unrestricted double" => $"WebIdlConversions.ToUnrestrictedDouble(engine, {varName})",
            "float" => $"WebIdlConversions.ToFloat(engine, {varName})",
            "unrestricted float" => $"WebIdlConversions.ToFloat(engine, {varName}, unrestricted: true)",
            "byte" => $"WebIdlConversions.ToByte(engine, {varName}, enforceRange: {type.EnforceRange.ToString().ToLower()}, clamp: {type.Clamp.ToString().ToLower()})",
            "long" => $"WebIdlConversions.ToInt32(engine, {varName}, enforceRange: {type.EnforceRange.ToString().ToLower()}, clamp: {type.Clamp.ToString().ToLower()})",
            "unsigned long" => $"WebIdlConversions.ToUint32(engine, {varName}, enforceRange: {type.EnforceRange.ToString().ToLower()}, clamp: {type.Clamp.ToString().ToLower()})",
            "short" => $"WebIdlConversions.ToInt16(engine, {varName}, enforceRange: {type.EnforceRange.ToString().ToLower()}, clamp: {type.Clamp.ToString().ToLower()})",
            "unsigned short" => $"WebIdlConversions.ToUint16(engine, {varName}, enforceRange: {type.EnforceRange.ToString().ToLower()}, clamp: {type.Clamp.ToString().ToLower()})",
            "octet" => $"WebIdlConversions.ToUint8(engine, {varName}, enforceRange: {type.EnforceRange.ToString().ToLower()}, clamp: {type.Clamp.ToString().ToLower()})",
            "long long" => $"WebIdlConversions.ToInt64(engine, {varName}, enforceRange: {type.EnforceRange.ToString().ToLower()}, clamp: {type.Clamp.ToString().ToLower()})",
            "unsigned long long" => $"WebIdlConversions.ToUint64(engine, {varName}, enforceRange: {type.EnforceRange.ToString().ToLower()}, clamp: {type.Clamp.ToString().ToLower()})",
            "BufferSource" => $"WebIdlConversions.ToBufferSource(engine, {varName})",
            "ArrayBuffer" => $"WebIdlConversions.ToBufferSource(engine, {varName}, allowArrayBuffer: true, requireArrayBuffer: true)",
            "ArrayBufferView" or "DataView" => $"WebIdlConversions.ToBufferSource(engine, {varName}, allowArrayBuffer: false)",
            "object" => $"WebIdlConversions.RequireObject({varName})",
            _ when type.Kind == IdlTypeKind.Dictionary => $"{type.Name}.FromScriptValue(engine, {varName})",
            _ when type.Kind == IdlTypeKind.Interface => $"WebIdlConversions.UnwrapHostObject<I{type.Name}Target>(engine, {varName}, \"{type.Name}\")",
            _ when type.Kind == IdlTypeKind.TypedArray => GenerateTypedArrayConversion(type, varName),
            _ when type.Kind == IdlTypeKind.Sequence => GenerateSequenceConversion(type, varName),
            "any" => varName,
            _ => varName,
        };
    }

    private static string GenerateToScriptValue(IdlType type, string expr)
    {
        type = Resolve(type);
        if (type.IsNullable)
        {
            var nonNullable = type with { IsNullable = false };
            if (MapCsType(nonNullable) == "ScriptValue")
            {
                var valueExpr = $"{expr}.Value";
                return $"{expr}.HasValue ? {GenerateToScriptValue(nonNullable, valueExpr)} : ScriptValue.Null";
            }
            if (IsGeneratedValueType(nonNullable))
            {
                var valueExpr = $"{expr}.Value";
                return $"{expr}.HasValue ? {GenerateToScriptValue(nonNullable, valueExpr)} : ScriptValue.Null";
            }
            return $"{expr} is null ? ScriptValue.Null : {GenerateToScriptValue(nonNullable, expr)}";
        }
        if (type.Kind == IdlTypeKind.Sequence)
        {
            var itemExpr = GenerateToScriptValue(type.SubTypes![0], "item");
            return $"WebIdlConversions.ToScriptSequence(engine, {expr}, item => {itemExpr})";
        }
        if (type.Kind == IdlTypeKind.Dictionary)
            return $"{expr}.ToScriptValue(engine)";
        if (type.Kind == IdlTypeKind.TypedArray)
            return $"{expr}.Value";
        return type.Name switch
        {
            "boolean" => $"ScriptValue.FromBoolean({expr})",
            "DOMString" or "ByteString" or "USVString" => $"ScriptValue.FromString({expr})",
            "double" or "unrestricted double" or "float" or "unrestricted float" or "long" or "unsigned long" or
            "short" or "unsigned short" or "octet" or "byte" or "long long" or "unsigned long long" =>
                $"ScriptValue.FromNumber({expr})",
            "BufferSource" or "ArrayBuffer" or "ArrayBufferView" or "DataView" => $"{expr}.Value",
            _ when type.Kind == IdlTypeKind.Interface => $"engine is null ? throw WebIdlException.TypeError(\"An engine is required to wrap {type.Name}\") : WebIdlConversions.WrapHostObject(engine, {type.Name}Binding.CreateTemplate(engine), {expr})",
            _ when type.Kind == IdlTypeKind.Enum => $"ScriptValue.FromString({expr})",
            "object" => expr,
            "any" => expr,
            _ => $"ScriptValue.FromObject({expr})",
        };
    }

    private static string FormatDefaultValue(IdlType type, string def)
    {
        type = Resolve(type);
        if (def == "[]") return type.Name == "sequence" ? $"Array.Empty<{MapCsType(type.SubTypes![0])}>()" : "Array.Empty<object>()";
        if (def == "{}") return type.Name == "record" ? $"new Dictionary<{MapCsType(type.SubTypes![0])}, {MapCsType(type.SubTypes![1])}>()" : "new object()";
        if (type.Name is "DOMString" or "ByteString" or "USVString") return $"\"{def.Trim('"')}\"";
        return def;
    }

    private static string GenerateSequenceConversion(IdlType type, string varName)
    {
        var itemConversion = GenerateValueConversion(type.SubTypes![0], "item");
        return $"WebIdlConversions.ToSequence(engine, {varName}, item => {itemConversion})";
    }

    private static bool IsGeneratedValueType(IdlType type) => type.Name is
        "boolean" or "byte" or "octet" or "short" or "unsigned short" or "long" or "unsigned long" or
        "long long" or "unsigned long long" or "float" or "unrestricted float" or "double" or
        "unrestricted double" or "BufferSource" or "ArrayBuffer" or "ArrayBufferView" or "DataView";

    private static string GenerateTypedArrayConversion(IdlType type, string varName)
    {
        if (type.Name is "ArrayBufferView")
            return $"WebIdlConversions.ToBufferSource(engine, {varName}, allowArrayBuffer: false)";
        if (type.Name is "DataView")
            return $"WebIdlConversions.ToBufferSource(engine, {varName}, allowArrayBuffer: false, requiredKind: ScriptBufferSourceKind.DataView)";
        var kind = type.Name switch
        {
            "Int8Array" => "Int8", "Uint8Array" => "Uint8", "Uint8ClampedArray" => "Uint8Clamped",
            "Int16Array" => "Int16", "Uint16Array" => "Uint16", "Int32Array" => "Int32", "Uint32Array" => "Uint32",
            "Float16Array" => "Float16", "Float32Array" => "Float32", "Float64Array" => "Float64",
            "BigInt64Array" => "BigInt64", "BigUint64Array" => "BigUint64", _ => null
        };
        return kind is null
            ? $"WebIdlConversions.ToBufferSource(engine, {varName}, allowArrayBuffer: false)"
            : $"WebIdlConversions.ToBufferSource(engine, {varName}, allowArrayBuffer: false, requiredKind: ScriptBufferSourceKind.{kind})";
    }

    private static IdlType Resolve(IdlType type) => Resolve(type, new HashSet<string>(StringComparer.Ordinal));

    private static IdlType Resolve(IdlType type, HashSet<string> resolving)
    {
        if (_aliases.TryGetValue(type.Name, out var alias))
        {
            if (!resolving.Add(type.Name))
                throw new InvalidOperationException($"Cyclic WebIDL typedef alias involving '{type.Name}'.");
            var resolved = Resolve(alias, resolving);
            resolving.Remove(type.Name);
            return resolved with
            {
                IsNullable = type.IsNullable || resolved.IsNullable,
                EnforceRange = type.EnforceRange || resolved.EnforceRange,
                Clamp = type.Clamp || resolved.Clamp
            };
        }
        if (_enumNames.Contains(type.Name) && type.Kind == IdlTypeKind.Interface)
            return type with { Kind = IdlTypeKind.Enum };
        if (_dictionaryNames.Contains(type.Name) && type.Kind == IdlTypeKind.Interface)
            return type with { Kind = IdlTypeKind.Dictionary };
        return type;
    }

    private static int RequiredArgumentCount(IdlOperation op) =>
        op.Arguments.TakeWhile(a => !a.IsOptional && !a.IsVariadic).Count();

    private static string OverloadShapeCondition(IdlOperation op, IReadOnlyList<IdlOperation> overloads)
    {
        var checks = op.Arguments.Where(a => !a.IsOptional && !a.IsVariadic)
            .Select((a, i) => IsDistinguishingArgument(op, overloads, i)
                ? OverloadArgumentCondition(a.Type, $"args[{i}]", overloads.Where(other => other != op && i < other.Arguments.Count).Select(other => other.Arguments[i].Type))
                : null)
            .Where(x => x is not null);
        var result = string.Join(" && ", checks);
        return result.Length == 0 ? "" : $" && {result}";
    }

    private static bool IsDistinguishingArgument(IdlOperation op, IReadOnlyList<IdlOperation> overloads, int index)
    {
        if (index >= op.Arguments.Count) return false;
        var name = Resolve(op.Arguments[index].Type).Name;
        return overloads.Any(other => other != op && index < other.Arguments.Count &&
            Resolve(other.Arguments[index].Type).Name != name);
    }

    private static string? OverloadArgumentCondition(IdlType input, string value, IEnumerable<IdlType> alternatives)
    {
        var type = Resolve(input);
        var alternativeTypes = alternatives.Select(Resolve).ToArray();
        if (type.Name is "BufferSource" or "ArrayBuffer" or "ArrayBufferView" or "DataView" || type.Kind == IdlTypeKind.TypedArray)
            return type.IsNullable
                ? $"{value}.IsNullOrUndefined || (engine is not null && engine.TryGetBufferSourceInfo({value}, out _))"
                : $"engine is not null && engine.TryGetBufferSourceInfo({value}, out _)";
        if (type.Kind == IdlTypeKind.Interface)
            return $"engine is not null && engine.TryGetHostTarget({value}, out var overloadTarget) && overloadTarget is I{type.Name}Target";
        if (type.Kind == IdlTypeKind.Sequence)
            return $"{value}.IsObject";
        if (type.Name is "boolean") return $"{value}.IsBoolean";
        if (type.Kind == IdlTypeKind.Primitive && alternativeTypes.Any(t => t.Name is "BufferSource" or "ArrayBuffer" or "ArrayBufferView" || t.Kind == IdlTypeKind.TypedArray))
        {
            var nullableAlternative = alternativeTypes.Any(t => t.IsNullable);
            var nullGuard = nullableAlternative ? $"!{value}.IsNullOrUndefined && " : "";
            return $"{nullGuard}(engine is null || !engine.TryGetBufferSourceInfo({value}, out _))";
        }
        // Primitive WebIDL numeric arguments are coercible and therefore are not
        // useful overload discriminators except when excluding a branded object.
        return null;
    }

    private static string ToPascalCase(string name)
    {
        if (string.IsNullOrEmpty(name)) return name;
        if (name.Length == 1) return char.ToUpperInvariant(name[0]).ToString();
        return char.ToUpperInvariant(name[0]) + name[1..];
    }

    private static string ToCamelCase(string name)
    {
        if (string.IsNullOrEmpty(name)) return name;
        if (name.Length == 1) return char.ToLowerInvariant(name[0]).ToString();
        return char.ToLowerInvariant(name[0]) + name[1..];
    }
